// Helper to get nested value by path, fallback to ES
export function getTranslation(lang: Lang, path: string): string {
  const keys = path.split(".");
  let cur: unknown = translations[lang];
  for (const k of keys) {
    if (cur && typeof cur === "object" && k in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[k];
    } else {
      cur = undefined;
      break;
    }
  }
  if (typeof cur === "string") return cur;
  // Fallback to ES
  let fallback: unknown = translations.es;
  for (const k of keys) {
    if (fallback && typeof fallback === "object" && k in (fallback as Record<string, unknown>)) {
      fallback = (fallback as Record<string, unknown>)[k];
    } else {
      fallback = undefined;
      break;
    }
  }
  if (typeof fallback === "string") return fallback;
  return path;
}

export function t(lang: Lang, path: string, params?: Record<string, string | number>): string {
  let str = getTranslation(lang, path);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}

